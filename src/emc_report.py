    def fig_85(self):
        """Marginal (leave-one-out) curves along BOTH rays from the cached ablation spectra.

        LER fractions per code + 1/Λ deficit shares, with ±1σ bands — binomial errors
        propagated exactly as in the §7.5/§8 boxes (hypot of the two relative errors; the
        full-mix/ablation correlation is neglected, same convention). Bands are STATISTICAL
        only: the zero-bin truncation exposure is not drawn — the boxes' [lo, hi] verdicts
        carry it. y-range clamped; a band swallowing its curve = noise-dominated region
        (prep, and everything at low p).
        """
        p_grid, P_LAM = self.p_grid, self.P_LAM

        def _eps(L, se, rounds):
            Lc = np.clip(L, 0.0, 1.0 - 1e-12)
            g = (1.0 - Lc) ** (1.0 / rounds - 1.0) / rounds
            return 1.0 - (1.0 - Lc) ** (1.0 / rounds), g * se

        # spectrum lookup per ray: (mix, code) -> FailureSpectrum, mix in {"full"} ∪ ABLATED
        def _spec_sym(m, c):
            if m == "full":
                return (self.tech1 if c == "18" else self.tech1_72)["full symmetric"]["spec"]
            return (self.tech1_abl if c == "18" else self.tech1_72_abl)[m]["spec"]

