    def lambda_table(self):
        """Point-Λ per channel at p* + true-threshold crossings from the f5-fit curves.

        Λ evaluation point matches the §6 budget's p*, deep in the suppression regime. Point-Λ
        uses the REWEIGHTED measured spectra (both codes sampled from w=1 through their
        onsets), avoiding cross-fit extrapolation drift; the f5-based value is printed as a
        cross-check. The ±σ column propagates the binomial errors of both spectra. Honesty
        note: zero-failure onset bins make the reweighted ε72 a lower bound → Λ an upper bound
        (a large reweighted-vs-fit gap flags this; the §7.5 box quantifies it per channel via
        the rule-of-three zero-bin headroom).
        """
        p_grid, P_LAM = self.p_grid, self.P_LAM
        self.eps18 = {m: per_round(self.tech1[m]["LER"], self.ROUNDS) for m in self.MODELS}
        self.eps72 = {m: per_round(self.tech1_72[m]["LER"], self.ROUNDS72) for m in self.MODELS}
        eps18, eps72 = self.eps18, self.eps72

        i_lam = int(np.argmin(np.abs(p_grid - P_LAM)))
        rows7, inv7 = [], {}
        print(f"{'channel':16s} {'p_th (ε18=ε72)':>15} {'Λ(p*)':>9} {'±σ':>8} {'Λ(fit)':>9} "
              f"{'p*/p_th':>9}     (p* = {P_LAM})")
        for m in self.MODELS:
            pth = crossing_p(p_grid, eps18[m], eps72[m])
            inv, inv_se, inv_lo, inv_hi = self.inv_lambda_stats(
                self.tech1[m]["spec"], self.tech1_72[m]["spec"], P_LAM)
            inv7[m] = (inv, inv_se, inv_lo, inv_hi)
            lam, lam_se = 1.0 / inv, inv_se / inv**2
            lam_fit = float(eps18[m][i_lam] / eps72[m][i_lam])
            rows7.append((m, pth, lam))
            pths = f"{pth:.4f}" if pth else f">{p_grid.max():.3g}"
            term = f"{P_LAM/pth:.3f}" if pth else f"<{P_LAM/p_grid.max():.3f}"
            print(f"{m:16s} {pths:>15} {lam:9.3g} {lam_se:8.2g} {lam_fit:9.3g} {term:>9}")
        self.rows7, self.inv7 = rows7, inv7

        self.lam_full = dict((m, l) for m, _, l in rows7)["full symmetric"]
        print(f"\nΛ_full(p*) = {self.lam_full:.3g}  →  per-(+2-distance)-step λ = √Λ = "
              f"{np.sqrt(self.lam_full):.3g}  (d: 4→8 is two steps)")
        inv_lam = 1.0 / self.lam_full
        terms = {m: P_LAM / pth for m, pth, _ in rows7 if pth is not None and m != "full symmetric"}
        spam_term = terms.get("meas only", 0) + terms.get("prep only", 0)
        print(f"Willow identity check at p*: 1/Λ_full = {inv_lam:.3f}  vs  Σᵢ p*/p_th,i = "
              f"{sum(terms.values()):.3f}"
              f"   (CZ {terms.get('CZ only', float('nan')):.3f}, SPAM {spam_term:.3f})")
        print("residual = mixed-channel faults (isolated channels cannot see them — see §1/§5); "
              "Σ < 1/Λ_full means the additive budget under-covers by that share.")

