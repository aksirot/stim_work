    # --- §6 the budget ------------------------------------------------------------------

    def ler_at(self, d, p):              # reweighted measured spectrum at scalar p (no extrapolation)
        return float(reweight_spectrum(d["spec"], [p]).P_logical[0])

    def split_at(self, name, p):         # Technique-III splitting estimate at p (log-log interpolated)
        sp, sP = self.tech3[name]["sp"], self.tech3[name]["sP"]
        return float(np.exp(np.interp(np.log(p), np.log(sp), np.log(sP))))

    def budget_table(self):
        P_STAR, p_grid = self.P_STAR, self.p_grid
        self.L_full, L_full_se, _ = self.rw_stats(self.tech1["full symmetric"]["spec"], P_STAR)
        L_full = self.L_full
        S_full = self.split_at("full symmetric", P_STAR)
        rows = []
        for ch in self.CHANNELS:
            iso = self.ler_at(self.tech1[ch], P_STAR) / L_full
            La, La_se, _ = self.rw_stats(self.tech1_abl[self.ABL_OF[ch]]["spec"], P_STAR)
            marg = 1.0 - La / L_full
            marg_se = (La / L_full) * float(np.hypot(La_se / La, L_full_se / L_full))
            iso_split = self.split_at(ch, P_STAR) / S_full
            pth = pseudo_threshold(p_grid, self.tech1[ch]["LER"])
            rows.append((ch, iso, marg, iso_split, pth, marg_se))
        self.rows6 = rows

        print(f"error budget at p* = {P_STAR}   (LER_full: reweighted {L_full:.3e}, "
              f"splitting {S_full:.3e})")
        print(f"{'channel':12s} {'isolated':>9} {'iso(split)':>10} {'marginal':>9} {'±σ':>6} "
              f"{'p_pth':>9} {'p*/p_pth':>9}")
        for ch, iso, marg, iso_split, pth, mse in rows:
            pths = f"{pth:.4f}" if pth else f">{p_grid.max():.3g}"    # no break-even crossing in-grid
            term = f"{P_STAR/pth:.3f}" if pth else f"<{P_STAR/p_grid.max():.3f}"  # bound, not a blank
            print(f"{ch:12s} {iso:9.3f} {iso_split:10.3f} {marg:9.3f} {mse:6.3f} {pths:>9} {term:>9}")
        self.mixing = 1.0 - sum(r[1] for r in rows)
        spam_iso = sum(r[1] for r in rows if r[0] in ("meas only", "prep only"))
        spam_marg = sum(r[2] for r in rows if r[0] in ("meas only", "prep only"))
        idle_iso = sum(r[1] for r in rows if "idle" in r[0])
        idle_marg = sum(r[2] for r in rows if "idle" in r[0])
        print(f"{'mixing':12s} {self.mixing:9.3f}                             "
              f"(1 - sum isolated: cross-channel faults)")
        print(f"{'SPAM':12s} {spam_iso:9.3f} {'':10s} {spam_marg:9.3f}         (meas + prep combined)")
        print(f"{'idle total':12s} {idle_iso:9.3f} {'':10s} {idle_marg:9.3f}         "
              f"(gate + meas idle combined)")
        print(f"sum(marginal) = {sum(r[2] for r in rows):.3f}  "
              f"(>1 <=> shared mixed faults; Google renormalizes)")
        print(f"Willow-form sum: {sum(P_STAR / r[4] for r in rows if r[4]):.3f} = "
              + " + ".join(f"{P_STAR/r[4]:.3f} ({r[0].replace(' only', '')})" for r in rows if r[4])
              + ("   [all terms < 1: genuinely sub-threshold]"
                 if all(P_STAR / r[4] < 1 for r in rows if r[4])
                 else "   [WARNING: a term >= 1 — p* is not below every pseudo-threshold]"))

