    # --- estimators shared by the sections --------------------------------------------

    def rw_stats(self, spec, p):
        """Reweighted-measured-spectrum LER at scalar p: (value, statistical SE, zero-bin headroom).

        SE propagates the per-bin binomial errors of the sampled f(w). `headroom` is how much
        the value could RISE if every sampled-but-zero-failure bin actually sat at its
        rule-of-three upper bound f(w) < 3/T(w). EVERY zero bin is priced, including those
        below tech2's D: D is the PERFECT-decoder floor, but the actual decoder miscorrects
        (returns a wrong-coset correction heavier than the fault) at rates the spectra measure
        directly — e.g. f(1) > 0 on the full 18-code mix — so an empty low-w bin is unresolved
        statistics, not a structural zero.
        """
        v = reweight_spectrum(spec, [p])
        up = FailureSpectrum(weights=spec.weights, trials=spec.trials,
                             failures=[f if f > 0 else min(3, t)
                                       for f, t in zip(spec.failures, spec.trials)],
                             n_expanded=spec.n_expanded, q_base=spec.q_base, p_ref=spec.p_ref)
        head = float(reweight_spectrum(up, [p]).P_logical[0]) - float(v.P_logical[0])
        return float(v.P_logical[0]), float(v.P_logical_se[0]), head

    def eps_stats(self, spec, p, rounds):
        """Per-round ε at p with SE and zero-bin headroom (delta method through 1-(1-L)^{1/r})."""
        L, se, head = self.rw_stats(spec, p)
        g = (1.0 - min(L, 1.0 - 1e-12)) ** (1.0 / rounds - 1.0) / rounds
        return float(per_round(np.asarray([L]), rounds)[0]), g * se, g * head

    def inv_lambda_stats(self, spec18, spec72, p):
        """1/Λ = ε72/ε18 at p: (value, SE, low, high) — low/high span the zero-bin truncation."""
        e18, s18, h18 = self.eps_stats(spec18, p, self.ROUNDS)
        e72, s72, h72 = self.eps_stats(spec72, p, self.ROUNDS72)
        inv = e72 / e18
        se = inv * float(np.hypot(s18 / e18, s72 / e72))
        return inv, se, e72 / (e18 + h18), (e72 + h72) / e18

