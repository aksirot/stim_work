def fig_generations_spectra(model="full_symmetric", p_grid=None):
    """Full IS failure spectrum f(w) and the reweighted LER(p) it implies, per decoder.

    Left: every measured bin, so the sub-onset band and the shoulder are visible in one
    picture. Right: the same spectra reweighted to a range of physical error rates —
    this is the quantity the campaign actually quotes, and it shows what the sub-onset
    improvement is worth in LER terms.
    """
    if p_grid is None:
        p_grid = np.geomspace(1e-4, 1e-2, 40)
    fig, (axL, axR) = plt.subplots(1, 2, figsize=(13, 4.8))
    for label, run_name, colour in GEN_DIRS:
        spec = _gen_fullspec(run_name, f"tech1_72__{model}")
        if spec is None:
            continue
        W = np.asarray(spec.weights); F = np.asarray(spec.failures, float)
        T = np.asarray(spec.trials, float)
        hit = F > 0
        r = F[hit] / T[hit]
        se = 1.96 * np.sqrt(r * (1 - r) / T[hit])
        axL.errorbar(W[hit], r, yerr=[np.minimum(se, r * 0.999), se], fmt="o-", ms=3.5,
                     lw=1.2, capsize=1.5, color=colour, label=label)
        z = (~hit) & (T > 0)
        if z.any():
            axL.plot(W[z], 3.0 / T[z], "v", ms=5, mfc="none", mec=colour, mew=1.2)
        # The reweighted LER counts only MEASURED failures, so a zero-failure bin
        # contributes exactly zero -> the curve is optimistic wherever the sampling could
        # not resolve the rate. Draw the honest band: the solid line assumes those bins
        # are truly empty, the upper edge prices each at its rule-of-three bound 3/T.
        filled = fill_spectrum(spec)
        L = [float(reweight_spectrum(filled, [p]).P_logical[0]) for p in p_grid]
        up = FailureSpectrum(weights=filled.weights, trials=filled.trials,
                             failures=[f if f > 0 else min(3, t)
                                       for f, t in zip(filled.failures, filled.trials)],
                             n_expanded=filled.n_expanded, q_base=filled.q_base,
                             p_ref=filled.p_ref)
        L_hi = [float(reweight_spectrum(up, [p]).P_logical[0]) for p in p_grid]
        axR.plot(p_grid, L, "-", lw=2, color=colour, label=label)
        axR.fill_between(p_grid, L, L_hi, color=colour, alpha=0.18, lw=0)
    for ax in (axL, axR):
        ax.set_yscale("log"); ax.grid(alpha=0.3, which="both")
    axL.set_xscale("log")
    axL.set_xlabel("fault weight w"); axL.set_ylabel("f(w)")
    axL.set_title(f"IS failure spectrum — {model.replace('_', ' ')}", fontsize=10)
    axL.legend(fontsize=8)
    axR.set_xscale("log")
    axR.axvline(5e-4, color="0.6", ls=":", lw=1)
    axR.text(5.3e-4, axR.get_ylim()[0] * 3, "p*", color="0.4", fontsize=8)
    axR.set_xlabel("physical error rate p"); axR.set_ylabel(r"$P_{\rm logical}$ (reweighted)")
    axR.set_title("reweighted LER — solid: empty bins counted as zero; "
                  "shaded: each priced at its 3/T bound", fontsize=10)
    axR.legend(fontsize=8)
    plt.tight_layout(); plt.show()


def generations_lambda(p_star=5e-4, rounds18=None, rounds72=None,
                       model18="tech1__full_symmetric", model72="tech1_72__full_symmetric"):
    """Λ = ε18/ε72 per decoder generation, with the zero-bin truncation band.

    The 18-code runs the baseline decoder in every campaign (ghw's wide gamma interval is
    measured-broken there), so Λ moves only through the 72-code — i.e. this is exactly the
    system-level Λ the campaign quotes, and the improvement is the decoder's.
    """
    # Round counts come from the campaign manifest, never hardcoded: epsilon is PER ROUND,
    # so a wrong count silently rescales every Lambda. This campaign runs 2 rounds on the
    # [[18,4,4]] code and 4 on the [[72,4,8]].
    if rounds18 is None or rounds72 is None:
        man = json.loads((run_dir("error_model_comparison_18_4_4") /
                          "config__manifest.json").read_text(encoding="utf-8"))["config"]
        rounds18 = rounds18 if rounds18 is not None else man["rounds"]
        rounds72 = rounds72 if rounds72 is not None else man["rounds72"]
    s18 = _gen_fullspec("error_model_comparison_18_4_4", model18)
    v18 = reweight_spectrum(s18, [p_star])
    e18 = float(per_round(np.asarray([float(v18.P_logical[0])]), rounds18)[0])
    print(f"Λ = ε18 / ε72  at p* = {p_star}   (18-code = baseline decoder throughout; "
          f"{rounds18} rounds on the 18-code, {rounds72} on the 72-code)")
    print(f"  ε18 = {e18:.3e}\n")
    print(f"{'72-code decoder':14s} {'ε72':>12s} {'Λ':>10s} {'Λ floor':>10s}   (floor prices"
          f" every zero bin at 3/T)")
    for label, run_name, _ in GEN_DIRS:
        s72 = _gen_fullspec(run_name, model72)
        if s72 is None:
            continue
        filled = fill_spectrum(s72)
        L = float(reweight_spectrum(filled, [p_star]).P_logical[0])
        up = FailureSpectrum(weights=filled.weights, trials=filled.trials,
                             failures=[f if f > 0 else min(3, t)
                                       for f, t in zip(filled.failures, filled.trials)],
                             n_expanded=filled.n_expanded, q_base=filled.q_base,
                             p_ref=filled.p_ref)
        L_hi = float(reweight_spectrum(up, [p_star]).P_logical[0])
        e72 = float(per_round(np.asarray([L]), rounds72)[0])
        e72_hi = float(per_round(np.asarray([L_hi]), rounds72)[0])
        print(f"{label:14s} {e72:12.3e} {e18/e72:10.0f} {e18/e72_hi:10.0f}")
    print("\nΛ is a RANGE, not a point: unmeasured (zero-failure) low-weight bins could "
          "each sit\nanywhere below their 3/T bound, and the floor column prices them all "
          "at that bound.")


def fig_weight_contributions(model="full_symmetric", p_lo=1e-5, p_hi=5e-3, w_max=20):
    """Which fault weights carry the logical error rate, as a function of p.

    LER(p) = sum_w P(W=w | p) f(w), so each weight's share is
    C(N,w) q^w (1-q)^(N-w) f(w) normalised over w. This is the picture behind the LER
    slope: the lightest weight with a NON-ZERO measured f(w) dominates as p falls, so a
    decoder with a sub-onset floor at w=3 scales as p^3 while a clean one recovers p^4.

    Colour is each weight's fractional contribution at that p; the white line is the
    contribution-weighted mean weight; the dashed line marks the perfect-decoder onset.
    """
    from scipy.stats import binom as _binom
    pg = np.geomspace(p_lo, p_hi, 90)
    fig, axes = plt.subplots(1, len(GEN_DIRS), figsize=(5.0 * len(GEN_DIRS), 4.2),
                             sharey=True)
    axes = np.atleast_1d(axes)
    for ax, (label, run_name, _) in zip(axes, GEN_DIRS):
        spec = _gen_fullspec(run_name, f"tech1_72__{model}")
        if spec is None:
            ax.set_visible(False)
            continue
        s = fill_spectrum(spec)
        W = np.asarray(s.weights); F = np.asarray(s.failures, float)
        T = np.asarray(s.trials, float)
        keep = W <= w_max
        W, f_w = W[keep], np.divide(F[keep], T[keep], out=np.zeros(keep.sum()),
                                    where=T[keep] > 0)
        M = np.zeros((len(W), len(pg)))
        for j, p in enumerate(pg):
            q = s.q_base * (p / s.p_ref)
            contrib = _binom.pmf(W, s.n_expanded, q) * f_w
            tot = contrib.sum()
            M[:, j] = contrib / tot if tot > 0 else 0.0
        im = ax.pcolormesh(pg, W, M, shading="nearest", cmap="viridis",
                           vmin=0, vmax=max(M.max(), 1e-9))
        mean_w = (M * W[:, None]).sum(axis=0)
        ax.plot(pg, mean_w, "-", color="white", lw=2)
        w_lo = W[f_w > 0].min() if (f_w > 0).any() else None
        if w_lo is not None:
            ax.axhline(w_lo, color="crimson", ls="-", lw=1.4)
            ax.text(pg[2], w_lo + 0.4, f"lightest measured failure: w={w_lo}",
                    color="crimson", fontsize=8)
        ax.axhline(4, color="w", ls="--", lw=1.0, alpha=0.8)
        ax.set_xscale("log")
        ax.set_xlabel("physical error rate p")
        ax.set_title(label, fontsize=10)
    axes[0].set_ylabel("fault weight w")
    fig.colorbar(im, ax=list(axes), label="share of LER at that p", pad=0.02)
    fig.suptitle(f"[[72,4,8]] {model.replace('_', ' ')} — which fault weights carry the "
                 "logical error rate\n(white: mean contributing weight; dashed: perfect-"
                 "decoder onset w0=4; red: lightest weight this decoder actually fails)",
                 fontsize=11, y=1.04)
    plt.show()


def ler_slope_table(model="full_symmetric",
                    ranges=((1e-5, 1e-4), (1e-4, 5e-4), (2e-4, 1e-3), (1e-3, 5e-3))):
    """Local log-log slope d log LER / d log p — i.e. the effective exponent LER ~ p^k.

    Asymptotically k -> the lightest fault weight the decoder fails, so a sub-onset floor
    does not merely add an offset: it DEGRADES THE EXPONENT, and the penalty grows without
    limit as p falls.
    """
    hdr = "  ".join(f"{f'{a:.0e}-{b:.0e}':>12s}" for a, b in ranges)
    print(f"{'decoder':10s} {hdr}   lightest failing w")
    for label, run_name, _ in GEN_DIRS:
        spec = _gen_fullspec(run_name, f"tech1_72__{model}")
        if spec is None:
            continue
        s = fill_spectrum(spec)
        cells = []
        for a, b in ranges:
            pg = np.geomspace(a, b, 6)
            L = np.array([float(reweight_spectrum(s, [p]).P_logical[0]) for p in pg])
            cells.append(f"{np.polyfit(np.log(pg), np.log(L), 1)[0]:12.2f}")
        w_lo = min(w for w, f in zip(s.weights, s.failures) if f > 0)
        print(f"{label:10s} " + "  ".join(cells) + f"   w = {w_lo}")
    print("\nThe leftmost column is closest to asymptotic. A decoder failing at w=3 scales")
    print("as p^3; one clean to the true onset recovers p^4 — the code's own scaling.")


def _weight_map_panel(ax, spec, p_grid, w_max, onset):
    """Shared drawing for the weight-vs-p contribution maps. Returns the mesh handle."""
    from scipy.stats import binom as _binom
    s = fill_spectrum(spec)
    W = np.asarray(s.weights); F = np.asarray(s.failures, float); T = np.asarray(s.trials, float)
    keep = (W <= w_max) & (T > 0)
    W = W[keep]
    f_w = F[keep] / T[keep]
    M = np.zeros((len(W), len(p_grid)))
    for j, p in enumerate(p_grid):
        q = s.q_base * (p / s.p_ref)
        c = _binom.pmf(W, s.n_expanded, q) * f_w
        tot = c.sum()
        M[:, j] = c / tot if tot > 0 else 0.0
    im = ax.pcolormesh(p_grid, W, M, shading="nearest", cmap="viridis", vmin=0)
    ax.plot(p_grid, (M * W[:, None]).sum(axis=0), "-", color="white", lw=1.8)
    if (f_w > 0).any():
        w_lo = W[f_w > 0].min()
        ax.axhline(w_lo, color="crimson", lw=1.3)
        ax.text(p_grid[2], w_lo + 0.5, f"w={w_lo}", color="crimson", fontsize=7)
    ax.axhline(onset, color="w", ls="--", lw=0.9, alpha=0.85)
    ax.set_xscale("log")
    return im


def _weight_map(report, code="72", models=None, p_lo=1e-5, p_hi=5e-3, w_max=20):
    """Companion to fig_spectrum_grid: WHICH fault weights carry the LER, versus p.

    The spectrum grid answers "how often does weight w fail?"; this answers "which w
    actually matters at a given physical error rate?" — the product of that failure
    fraction with the binomial weight of w at p, normalised. As p falls, the mass
    collapses onto the lightest weight with a NON-ZERO measured f(w), which is a property
    of the decoder, not of the code: it sets the exponent of LER ~ p^k.
    """
    models = list(models or report.MODELS)
    prefix = "tech1_72__" if code == "72" else "tech1__"
    onset = (report.load(f"tech2_72__full_symmetric" if code == "72"
                         else "tech2__full_symmetric")["D"] + 1) // 2
    p_grid = np.geomspace(p_lo, p_hi, 90)
    ncol = 3
    nrow = int(np.ceil(len(models) / ncol))
    fig, axes = plt.subplots(nrow, ncol, figsize=(5.3 * ncol, 3.6 * nrow),
                             sharex=True, sharey=True)
    axes = np.atleast_1d(axes).ravel()
    im = None
    for ax, m in zip(axes, models):
        try:
            r = report.load(f"{prefix}{slug(m)}")
        except FileNotFoundError:
            ax.set_visible(False)
            continue
        im = _weight_map_panel(ax, report.spectrum_of(r), p_grid, w_max, onset)
        ax.set_title(m, fontsize=10)
    for ax in axes[len(models):]:
        ax.set_visible(False)
    for i, ax in enumerate(axes[:len(models)]):
        if i % ncol == 0:
            ax.set_ylabel("fault weight w")
        if i >= len(models) - ncol:
            ax.set_xlabel("physical error rate p")
    if im is not None:
        fig.colorbar(im, ax=list(axes), label="share of LER at that p", pad=0.02)
    label = "[[72,4,8]]" if code == "72" else "[[18,4,4]]"
    fig.suptitle(f"{label} — which fault weights carry the logical error rate\n"
                 f"(white: mean contributing weight; dashed: perfect-decoder onset "
                 f"w₀={onset}; red: lightest weight this decoder actually fails)",
                 fontsize=11, y=1.02)
    plt.show()


