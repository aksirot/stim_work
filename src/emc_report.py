    # --- the spectrum grid ----------------------------------------------------------------

    def _tech2_name(self, name):
        """The tech2 task carrying this spectrum's D/w0/f0* (or f0_lower), or None.

        D, w0 and the failing SETS are ray-independent (support-level combinatorics), but the
        onset FRACTION is not: mechanisms enter the expanded-uniform measure with
        rate-proportional multiplicities, so the ×5 ray re-weights the same failing sets. The
        asym 18-code mixes therefore load tech2_asym__*_18 (compute_f0_asym_18.py — reuses the
        symmetric D+L(D), redoes only the fail-count weighting). The [[72,4,8]] f0 is unpinned
        (no exact L(D) at that size) — the isolated/full tech2_72 tasks carry a LOWER-BOUND
        f0_lower (compute_f0_lower_72.py) and the ×5 asym 72 mixes their own ray-weighted one
        (tech2_asym__*_72, compute_f0_lower_asym_72.py — for the ablated mixes even D is a
        BP-OSD bound computed there); ablated-72 tasks have none."""
        if name.startswith("tech1_72_abl__"):
            return None                            # no ablated 72-code distance/onset computed
        if name.startswith("tech1_72__"):
            return name.replace("tech1_72__", "tech2_72__", 1)  # exact f0 unpinned; f0_lower here
        if name.startswith("tech1_abl__"):
            return name.replace("tech1_abl__", "tech2_abl__", 1)
        if name.startswith("tech1__"):
            return name.replace("tech1__", "tech2__", 1)
        if name.startswith("asym__"):              # _18: exact ray-weighted f0*; _72: f0_lower bound
            return name.replace("asym__", "tech2_asym__", 1)
        return None

    def _plot_spec(self, ax, name, color, label):
        try:
            r = self.load(name)
        except FileNotFoundError:
            return label                           # not cached (e.g. stale-decoder quarantine)
        s = self.spectrum_of(r)
        w, f, t = (np.asarray(a) for a in (s.weights, s.failures, s.trials))
        hit = f > 0
        fr = (f / t)[hit]
        # 95% binomial CI; lower bars clipped above zero so log-scale rendering survives
        # single-failure bins (whose CI floor would otherwise cross the axis)
        se = 1.96 * np.sqrt(np.clip(fr * (1 - fr), 0, None) / t[hit])
        ax.errorbar(w[hit], fr, yerr=[np.minimum(se, fr * 0.999), se], fmt=".-",
                    ms=4, lw=0.8, elinewidth=0.7, capsize=1.5, color=color, label=label)
        z = f == 0
        if z.any():
            ax.plot(w[z], 0.5 / t[z], "x", color=color, alpha=0.4)
        # ★ = Technique II's EXACT perfect-decoder onset fraction f0* at w0 (Prop.1 even D /
        # App.A.6 odd D). The ×5 asym rows load their OWN ray-weighted f0* (tech2_asym__*_18):
        # the failing sets are ray-independent but the fraction re-weights with the
        # rate-proportional multiplicities. ▲ (open, "f0* >=") = the [[72,4,8]] LOWER BOUND
        # f0_lower from a partial L(D) (compute_f0_lower_72.py) — exact f0* is unpinned at that
        # size, so panels get the floor.
        t2 = self._tech2_name(name)
        if t2:
            try:
                tr = self.load(t2)
                w0, f0, f0lo = tr.get("w0"), tr.get("f0"), tr.get("f0_lower")
                if w0 not in (None, "") and f0 not in (None, ""):
                    ax.plot(w0, float(f0), "*", color=color, ms=12, mec="k", mew=0.5, zorder=6)
                elif w0 not in (None, "") and f0lo not in (None, ""):
                    ax.plot(w0, float(f0lo), "^", color=color, ms=8, mfc="none", mec=color,
                            mew=1.4, zorder=6)
            except FileNotFoundError:
                pass
        try:
            if "fit" in r:
                fw = lambda wg, r=r: failure_spectrum_ansatz(
                    wg, a=1.0 - 2.0 ** -r["K"], model=r["fit"]["model"], **r["fit"]["params"])
            else:
                fw = fit_failure_spectrum(s, K=r["K"], model="f5", w0=None, f0=None).f
            wg = np.geomspace(1.0, float(w.max()), 200)
            y = np.asarray(fw(wg))
            ax.plot(wg[y > 0], y[y > 0], "--", lw=1.0, alpha=0.55, color=color)
        except Exception:
            pass                                   # too-sparse spectrum, no converged fit — dots only
        return None

