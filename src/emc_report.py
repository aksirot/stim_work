    def _spec(root, task):
        j = json.loads((root / f"{task}.json").read_text(encoding="utf-8"))["result"]
        keep = set(FailureSpectrum.__dataclass_fields__)
        return FailureSpectrum(**{k: v for k, v in j["spectrum"].items() if k in keep})

